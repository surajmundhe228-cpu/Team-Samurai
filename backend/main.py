@app.get("/api/hospitals")
def get_hospitals(
    query: Optional[str] = None,
    district: Optional[str] = None,
    emergency_only: bool = False
):
    """
    Search hospitals by name, location or district.

    Examples:

    /api/hospitals

    /api/hospitals?query=Supaul

    /api/hospitals?district=Supaul

    /api/hospitals?emergency_only=true
    """

    results = hospitals_data

    # Search by hospital name or location
    if query:
        query_lower = query.strip().lower()

        results = [
            hospital
            for hospital in results
            if (
                query_lower in hospital["name"].lower()
                or query_lower in hospital["location"].lower()
                or query_lower in hospital["district"].lower()
            )
        ]

    # Filter by district
    if district:
        district_lower = district.strip().lower()

        results = [
            hospital
            for hospital in results
            if hospital["district"].lower() == district_lower
        ]

    # Emergency-only filter
    if emergency_only:
        results = [
            hospital
            for hospital in results
            if hospital.get("emergency") is True
        ]

    return {
        "status": "success",
        "count": len(results),
        "hospitals": results
    }