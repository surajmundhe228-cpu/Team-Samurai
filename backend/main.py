@app.post("/api/alerts/check")
def api_check_threshold(payload: ThresholdInput):
    """
    Threshold Checker endpoint.

    Send risk/water data and receive whether an alert
    should fire along with the generated alert object.
    """

    data = (
        payload.model_dump()
        if hasattr(payload, "model_dump")
        else payload.dict()
    )

    result = check_threshold(data)

    if result["alert"] and result["alert_object"]:
        live_alerts_db.insert(
            0,
            result["alert_object"]
        )

    return {
        "status": "success",
        "alert": result["alert"],
        "risk_level": result["risk_level"],
        "data": result["alert_object"]
    }


@app.post("/api/alerts/scan-villages")
def api_scan_villages():
    """
    Scan all loaded villages and generate alerts
    for HIGH or CRITICAL risk.
    """

    v_list = (
        villages_data.get("villages", villages_data)
        if isinstance(villages_data, dict)
        else villages_data
    )

    generated = run_threshold_on_villages(
        v_list or []
    )

    for alert in generated:
        live_alerts_db.insert(
            0,
            alert
        )

    return {
        "status": "success",
        "generated_count": len(generated),
        "alerts": generated
    }


