@app.post("/api/sos")
def create_sos_request(request: SOSRequest):
    """
    Create an emergency SOS request.

    The request is stored in memory for the prototype.
    In production this should be stored in a secure database
    and connected to emergency/authority services.
    """

    request_data = (
        request.model_dump()
        if hasattr(request, "model_dump")
        else request.dict()
    )

    sos_id = (
        f"SOS-{datetime.utcnow().strftime('%Y%m%d%H%M%S')}"
        f"-{len(sos_requests_db) + 1}"
    )

    request_data["id"] = sos_id
    request_data["status"] = "ACTIVE"
    request_data["created_at"] = (
        datetime.utcnow().isoformat() + "Z"
    )

    sos_requests_db.insert(
        0,
        request_data
    )

    # Also create an alert for the notification system
    sos_alert = {
        "id": sos_id,
        "title": "Emergency SOS Request",
        "message": (
            request_data.get("message")
            or "Emergency SOS assistance requested."
        ),
        "type": "SOS",
        "severity": request_data.get(
            "severity",
            "CRITICAL"
        ).upper(),
        "district": request_data.get(
            "district",
            ""
        ),
        "village": request_data.get(
            "village")
            or request_data.get("location")
            or "",
        "latitude": request_data.get("latitude"),
        "longitude": request_data.get("longitude"),
        "issued_at": request_data["created_at"],
        "status": "Active",
        "source": "Emergency SOS",
        "alert": True
    }

    live_alerts_db.insert(
        0,
        sos_alert
    )

    return {
        "status": "success",
        "message": "SOS request received successfully.",
        "data": request_data
    }


